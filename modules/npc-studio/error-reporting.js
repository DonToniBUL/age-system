export function npcStudioUiRejection(message) {
  const error = new Error(message);
  error.name = "AgeNpcStudioUiRejection";
  error.code = "AGE_NPC_STUDIO_UI_REJECTION";
  return error;
}

export function isExpectedNpcStudioRejection(error) {
  if (error?.name === "AgeNpcStudioUiRejection") return true;
  return EXPECTED_NPC_STUDIO_REJECTION_CODES.has(String(error?.code ?? ""));
}

export function reportNpcStudioActionFailure(error, {
  consoleObject = globalThis.console,
  notifications = globalThis.ui?.notifications,
} = {}) {
  const expected = isExpectedNpcStudioRejection(error);
  const message = error?.message ?? String(error);
  if (!expected) consoleObject?.error?.("AGE System | NPC Studio action failed.", error);
  if (expected) (notifications?.warn ?? notifications?.error)?.call(notifications, message);
  else notifications?.error?.call(notifications, message);
  return expected;
}
